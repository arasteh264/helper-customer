function normalizePersian(value: string) {
  return value
    .trim()
    .toLocaleLowerCase("fa-IR")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[\u200c\u200f]/g, " ")
    .replace(/\s+/g, " ");
}

export function getRequestPlaceholders(
  specialtySlug: string,
  specialtyName: string,
  groupName: string,
): RequestPlaceholders {
  const normalizedSlug = specialtySlug.trim().toLowerCase();
  const bySlug = SPECIALTY_PLACEHOLDERS[normalizedSlug];
  const normalizedName = normalizePersian(specialtyName);
  const byName =
    bySlug ??
    Object.values(SPECIALTY_PLACEHOLDERS).find(
      (example) => normalizePersian(example.name) === normalizedName,
    );
  if (byName) {
    return {
      title: `مثلاً: ${byName.title}`,
      description: byName.description,
    };
  }

  const normalizedGroup = normalizePersian(groupName);
  const groupEntry = Object.entries(GROUP_PLACEHOLDERS).find(
    ([name]) => normalizePersian(name) === normalizedGroup,
  );
  if (groupEntry) return groupEntry[1];

  return {
    title: specialtyName
      ? `مثلاً: درخواست ${specialtyName}`
      : "مثلاً: خدمت موردنیازتان را کوتاه بنویسید",
    description: specialtyName
      ? `مثلاً: برای ${specialtyName} به متخصص نیاز دارم. محل یا وسیله‌ی موردنظر ... است و شرایط کار ... است. لطفاً درباره‌ی زمان انجام و هزینه‌ی احتمالی هماهنگ کنید.`
      : "مثلاً: توضیح دهید چه کاری لازم دارید، شرایط یا محل انجام کار چیست و چه زمانی برای انجام آن مناسب است.",
  };
}
